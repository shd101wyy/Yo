/**
 * Resolves a SomeType that was created as a placeholder for a recursive type.
 * When recur is called during compile-time evaluation and hits the temp cache,
 * a SomeType with recursiveTypeRef is returned. This function looks up the
 * actual resolved type from the function's cache.
 *
 * Resolution strategy (in order of preference):
 * 1. Look up the exact matching cache entry with resolved type
 * 2. Use context.SelfType if available (when inside struct/object definition)
 * 3. Use ANY resolved cache entry from the same function (same structure)
 */
function resolveRecursiveTypeRef(
  someType: SomeType,
  callerEnv: Environment,
  context?: EvaluatorContext
): Type | undefined {
  if (!someType.recursiveTypeRef) {
    return undefined;
  }

  const { functionValue, argValues } = someType.recursiveTypeRef;

  // Strategy 1: Look for the exact matching cache entry with resolved type
  const exactCache = functionValue.calledComptimeFunctionCaches.find(
    (cache) => {
      return (
        cache.argValues.length === argValues.length &&
        cache.argValues.every((argValue, index) => {
          const givenArgValue = argValues[index];

          if (isTypeValue(argValue) && isTypeValue(givenArgValue)) {
            return areTypesCompatible(
              { type: argValue.value, env: cache.env },
              { type: givenArgValue.value, env: callerEnv },
              true // requireExactMatch
            );
          }

          return areValuesEqual(
            { value: argValue, env: cache.env },
            { value: givenArgValue, env: callerEnv }
          );
        })
      );
    }
  );

  if (exactCache && isTypeValue(exactCache.value)) {
    // Check if it's not still a placeholder
    if (
      !(
        isSomeType(exactCache.value.value) &&
        exactCache.value.value.recursiveTypeRef
      )
    ) {
      return exactCache.value.value;
    }
  }

  // Strategy 2: Use context.SelfType if available
  if (context?.SelfType && isReferenceStructType(context.SelfType)) {
    return context.SelfType;
  }
  if (context?.SelfType && isStructType(context.SelfType)) {
    return context.SelfType;
  }

  // Strategy 3: Look for ANY resolved cache entry from the same function
  // All instantiations of the same type-generating function produce the same structure
  const anyResolvedCache = functionValue.calledComptimeFunctionCaches.find(
    (cache) => {
      if (!isTypeValue(cache.value)) return false;
      // Skip if still a placeholder
      if (isSomeType(cache.value.value) && cache.value.value.recursiveTypeRef) {
        return false;
      }
      // Found a resolved type
      return true;
    }
  );

  if (anyResolvedCache && isTypeValue(anyResolvedCache.value)) {
    return anyResolvedCache.value.value;
  }

  return undefined;
}

export function evaluateFunctionCall({
  expr,
  env,
  context,
  givenFunc,
  forMacroExpansion,
}: {
  expr: FnCallExpr;
  env: Environment;
  context: EvaluatorContext;
  givenFunc?: { type: Type; value: TypeValue | FunctionValue | undefined };
  forMacroExpansion?: boolean;
}): Expr {
  let func = expr.func;
  let args = expr.args;

  // For module method call
  let methodExpr: Expr | undefined = undefined;

  let functions: {
    type: Type;
    value?: Value;
    error?: Error | YoError;
    needsPointerConversion?: boolean;
    args?: Expr[]; // Store potentially modified args for this specific function
  }[] = [];
  if (givenFunc) {
    functions = [givenFunc];
  } else {
    if (exprIsFunctionCall(func)) {
      // Clear expectedType when the callee is a genuine call expression that
      // produces a callable (e.g., `.unwrap()` returning a function type).
      // The outer call's expected return type should not leak into the callee's
      // generic type resolution. For example, in
      //   `rules.get(0).unwrap()(state, a, b, c)`
      // where the outer call returns bool, passing expectedType=bool into
      // .unwrap() incorrectly binds T=bool instead of T=BlockRuleFn.
      //
      // However, DON'T clear expectedType when the callee is a property access
      // expression (`.X`), because enum variant constructors like `.Some(ptr)`
      // need expectedType to infer which enum type they belong to.
      const isPropertyAccess = exprIsFunctionCallOf(func, ".");
      const functionToCall = evaluateExpression({
        expr: func,
        env,
        context: isPropertyAccess
          ? { ...context }
          : {
              ...context,
              expectedType: undefined,
            },
      });
      func = functionToCall;

      // Propagate env from inner call evaluation so any temp variables
      // added (e.g., from evaluating get_list() in get_list()(idx))
      // are visible for subsequent arg evaluation and scope cleanup.
      if (func.$?.env) {
        env = func.$.env;
      }

      // Check if . property access for module method call
      if (!functionToCall.$?.type) {
        if (
          exprIsFunctionCall(functionToCall) &&
          exprIsFunctionCallOf(functionToCall, ".", 2)
        ) {
          const receiverArg = functionToCall.args[0]!;
          methodExpr = functionToCall.args[1]!;

          // The receiverArg should already be evaluated in the previous step
          // so it should have a type
          const receiverType = receiverArg.$?.type;
          if (!receiverType) {
            throw formatErrorMessage({
              token: receiverArg.token,
              errorMessage: `Expected to be evaluated.`,
            });
          }

          // Check if the receiver is a TypeValue (e.g., EvenNumber.try_from(...)),
          // which indicates a static method call on a type.
          const receiverValue = receiverArg.$?.value;
          const isStaticMethodCall = isTypeValue(receiverValue);

          // The methodExpr should also be evaluated already
          // so it should have a type
          if (exprIsAtom(methodExpr)) {
            // 1.add(3);
            const methodName = methodExpr.token.value;

            if (isStaticMethodCall) {
              // Static method call (e.g., EvenNumber.try_from(...))
              // Use getTypeTraitMethodsByNameFromEnv to find methods from impl'd traits
              const innerType = receiverValue.value;
              const methods = getTypeTraitMethodsByNameFromEnv({
                env,
                context,
                methodName,
                type: innerType,
              });

              functions = methods.map((method) => {
                // Static methods don't have a receiver argument - just pass the call args
                return {
                  type: method.type,
                  value: method.value,
                  args: args,
                };
              });
            } else {
              // Instance method call (e.g., value.add(...))

              // Memory safety gate: pointer arithmetic METHODS require
              // `unsafe(...)` (plans/archive/POINTER_OPERATORS_TO_TRAITS_AND_METHODS.md
              // — formerly the `&+`/`&-`/`&/` operators, whose spelling gate
              // lived in _expr.ts). Gated HERE because this is where the
              // receiver type is known: `add`/`sub`/`offset_from` are ordinary
              // method names on non-pointer types, and the `__yo_ptr_*`
              // builtin calls inside the prelude impl bodies are implicitly
              // unsafe-capable by path, so they can never fire on the user's
              // behalf. Mirrors Rust's `unsafe fn` on `<*const T>::add`.
              if (
                isPtrType(receiverType) &&
                (methodName === "add" ||
                  methodName === "sub" ||
                  methodName === "offset_from") &&
                !context.unsafeContext &&
                !isImplicitlyUnsafeCapableFile(expr.token.modulePath)
              ) {
                throw formatErrorMessage({
                  token: expr.token,
                  errorMessage: `Pointer arithmetic ('.${methodName}(...)') requires 'unsafe(...)'.

Wrap the expression as: unsafe(${exprToString(expr)})

Raw pointer arithmetic produces addresses usually destined to dereference, which may access invalid memory.`,
                });
              }

              // Get the method with the same name in the interface in the env
              const methods = getReceiverMethodsByNameFromEnv({
                env,
                context,
                methodName,
                receiverType,
                isInfixOperatorCall: false, // isInfixOperatorCall - property access allows auto pointer conversion
              });

              functions = methods.map((method) => {
                // If pointer conversion is needed, wrap the receiver in &()
                let methodArgs: Expr[];
                if (method.needsPointerConversion) {
                  // Create &(receiverArg) expression
                  // Note: The comptime type to runtime type conversion is handled
                  // in evaluateAddressCall (ptr_fns.ts) when &() is evaluated
                  const ampersandExpr: AtomExpr = {
                    tag: ExprTag.Atom,
                    token: receiverArg.token,
                    $: undefined,
                  };
                  ampersandExpr.token = {
                    ...receiverArg.token,
                    value: "&",
                    type: TokenType.Identifier,
                  };

                  const addressOfExpr: FnCallExpr = {
                    tag: ExprTag.FnCall,
                    func: ampersandExpr,
                    args: [receiverArg],
                    token: receiverArg.token,
                    $: undefined,
                  };

                  methodArgs = [addressOfExpr, ...args];
                } else {
                  methodArgs = [receiverArg, ...args];
                }

                return {
                  type: method.type,
                  value: method.value,
                  needsPointerConversion: method.needsPointerConversion,
                  args: methodArgs,
                };
              });
            }
          } else {
            // 1.(Add.add)(3);
            // Try to evaluate the methodExpr
            const nextExpr = evaluateExpression({
              expr: methodExpr,
              env,
              context: {
                ...context,
              },
            });
            if (nextExpr.$?.env) {
              env = nextExpr.$?.env;
            }
            methodExpr = nextExpr;

            const methodType = methodExpr.$?.type;
            const methodValue = methodExpr.$?.value;
            if (!methodType) {
              throw formatErrorMessage({
                token: methodExpr.token,
                errorMessage: `Expected to be a function.`,
              });
            }
            functions = [
              {
                type: methodType,
                value: methodValue,
              },
            ];
            // TODO: Autocase to reference/immutable reference
            args = [receiverArg, ...args];
          }
        } else {
          throw formatErrorMessage({
            token: func.token,
            errorMessage: `Expected type for function call, got ${exprToString(functionToCall)}`,
          });
        }
      } else {
        functions = [
          {
            type: functionToCall.$.type,
            value: functionToCall.$.value,
          },
        ];
      }
    } else {
      const functionName = func.token.value;

      // Check _ function
      if (functionName === "_") {
        const expectedType = context.expectedType;
        if (!expectedType || isSomeType(expectedType.type)) {
          // throw formatErrorMessage(
          //   func.token,
          //   `Failed to infer type for _ function`
          // );

          // Make it as an anonymous struct
          return evaluateAnonymousStructValue({
            expr,
            env,
            context,
          });
        }
        functions = [
          {
            type: typeOfType(expectedType.type),
            value: createTypeValue(expectedType.type),
          },
        ];

        // Add info to the func token
        func.$ = {
          env,
          type: functions[0]!.type,
          value: functions[0]!.value,
          pathCollection: [],
        };
      }
      // Infix operator is taken as an method call
      else if (stringIsOperator(functionName) && expr.isInfix) {
        const firstArg = args[0];
        if (!firstArg) {
          throw formatErrorMessage({
            token: func.token,
            errorMessage: `Expected first argument for operator, got:\n${exprToString(func)}`,
          });
        }
        // Evaluate the first argument to get its type
        // NOTE: We clear expectedType here because the operand type should be
        // determined by the operand itself, not by the return type expected from
        // the outer context (e.g., when `a == b` is used as argument to a function
        // expecting boolean, we shouldn't force the operands to be boolean)
        const evaluatedFirstArg = evaluateExpression({
          expr: firstArg,
          env,
          context: {
            ...context,
            expectedType: undefined,
          },
        });
        const receiverType = evaluatedFirstArg.$?.type;
        if (!receiverType) {
          throw formatErrorMessage({
            token: firstArg.token,
            errorMessage: `Expected to be evaluated.`,
          });
        }
        const methodName = functionName;
        methodExpr = func;
        // Get the method with the same name in the module/type in the env
        const moduleMethods = getReceiverMethodsByNameFromEnv({
          env,
          context,
          methodName,
          receiverType,
          isInfixOperatorCall: true, // isInfixOperatorCall - infix operators don't allow auto pointer conversion
        });
        functions = moduleMethods.map((method) => ({
          type: method.type,
          value: method.value,
          needsPointerConversion: method.needsPointerConversion,
        }));
        // No need to change the args
      }
      // Self function call
      else if (functionName === "Call" && context.SelfType) {
        const value = createTypeValue(context.SelfType);
        functions = [
          {
            type: value.type,
            value: value,
          },
        ];
      }
      // Normal function call
      else {
        const functionToCall = evaluateExpression({
          expr: func,
          env,
          context: {
            ...context,
          },
        });
        func = functionToCall;

        if (!functionToCall.$) {
          throw formatErrorMessage({
            token: func.token,
            errorMessage: `Failed to evaluate the callee:`,
          });
        }

        // Check if func is a struct value,
        // If yes, then we extract the Self from it.
        if (isSourceNamespaceType(functionToCall.$.type)) {
          const sourceNamespaceType = functionToCall.$.type;
          const selfIndex = sourceNamespaceType.fields.findIndex(
            (e) => e.label === "Call"
          );
          if (selfIndex < 0) {
            throw formatErrorMessage({
              token: func.token,
              errorMessage: `Calling a struct record value which does not have "Call" element is not allowed.`,
            });
          }
          const selfType = sourceNamespaceType.fields[selfIndex]!;
          if (selfType.assignedValue) {
            const selfValue = selfType.assignedValue;
            if (isTupleValue(selfValue)) {
              functions = selfValue.fields.map((element) => {
                return {
                  type: element.type,
                  value: element,
                };
              });
            } else {
              functions = [
                {
                  type: selfValue.type,
                  value: selfValue,
                },
              ];
            }
          } else {
            throw formatErrorMessage({
              token: func.token,
              errorMessage: `Calling a struct record value whose "Call" element doesn't have assigned value is not allowed.`,
            });
          }
        } else {
          /**
           * functionVariables might be of FunctionType, StructType, UnionType, and EnumVariant
           */
          functions = [
            {
              type: functionToCall.$.type,
              value: functionToCall.$.value,
            },
          ];
        }
      }
    }
  }

  // NOTE: Automatic CTFE candidate addition has been removed.
  // Use `comptime_fn(fn)` to explicitly create compile-time versions of functions.
  // This makes the behavior predictable - functions are called at runtime unless
  // explicitly declared as compile-time via comptime_fn().

  // Partial application with `_` placeholder.
  // When a comptime function is called with `_` in some argument positions,
  // create a new FunctionValue that captures the non-`_` arguments and
  // takes the `_` positions as parameters.
  // Examples:
  //   Result(_, MyError) → fn(comptime(__0) : Type) -> comptime(Type)
  //   add(1, _) → fn(comptime(__0) : i32) -> comptime(i32)
  {
    const hasPlaceholder = args.some(
      (arg) => exprIsAtom(arg) && arg.token.value === "_"
    );
    if (
      hasPlaceholder &&
      functions.length === 1 &&
      isFunctionValue(functions[0]!.value) &&
      isFunctionType(functions[0]!.type) &&
      functions[0]!.type.return.isCompileTimeOnly
    ) {
      const origFuncValue = functions[0]!.value as FunctionValue;
      const origFuncType = functions[0]!.type as FunctionType;
      const origParams = origFuncType.parameters;

      if (args.length !== origParams.length) {
        throw formatErrorMessage({
          token: func.token,
          errorMessage: `Partial application: expected ${origParams.length} argument(s), got ${args.length}`,
        });
      }

      // Build the new function's env, capturing non-`_` arg values
      let partialEnv = pushEnvFrame(env);

      // Store original function in env so the body can reference it
      const origFuncVarName = `__pa_fn_${randomId(env.modulePath)}`;
      {
        const { env: nextEnv } = addVariableToEnv({
          env: partialEnv,
          variable: {
            name: origFuncVarName,
            type: origFuncType,
            isCompileTimeOnly: true,
            value: [origFuncValue],
            token: func.token,
            initializedAtToken: func.token,
            consumedAtToken: undefined,
            isOwningTheRcValue: false,
          },
        });
        partialEnv = nextEnv;
      }

      // Classify args into free (_) and captured positions
      const newParams: FunctionParameter[] = [];
      const bodyArgs: Expr[] = [];

      for (let i = 0; i < args.length; i++) {
        const arg = args[i]!;
        const origParam = origParams[i]!;

        if (exprIsAtom(arg) && arg.token.value === "_") {
          // Free position — becomes a parameter of the new function
          const paramName = `__pa_${i}_${randomId(env.modulePath)}`;
          newParams.push({
            ...origParam,
            label: paramName,
          });
          // Body references this param
          bodyArgs.push({
            tag: ExprTag.Atom,
            token: {
              type: TokenType.Identifier,
              value: paramName,
              position: arg.token.position,
              modulePath: env.modulePath,
              inputString: env.inputString,
            },
          });
        } else {
          // Captured position — evaluate now and store in env
          const capturedName = `__pa_cap_${i}_${randomId(env.modulePath)}`;
          const evaluatedArg = evaluateExpression({
            expr: arg,
            env: partialEnv,
            context: { ...context },
          });
          if (!evaluatedArg.$) {
            throw formatErrorMessage({
              token: arg.token,
              errorMessage: `Failed to evaluate partial application argument`,
            });
          }
          partialEnv = evaluatedArg.$.env;

          const { env: nextEnv } = addVariableToEnv({
            env: partialEnv,
            variable: {
              name: capturedName,
              type: evaluatedArg.$.type,
              isCompileTimeOnly: true,
              value: evaluatedArg.$.value ? [evaluatedArg.$.value] : undefined,
              token: arg.token,
              initializedAtToken: arg.token,
              consumedAtToken: undefined,
              isOwningTheRcValue: false,
            },
          });
          partialEnv = nextEnv;

          // Body references the captured variable
          bodyArgs.push({
            tag: ExprTag.Atom,
            token: {
              type: TokenType.Identifier,
              value: capturedName,
              position: arg.token.position,
              modulePath: env.modulePath,
              inputString: env.inputString,
            },
          });
        }
      }

      // Create body: call original function with mixed args
      const bodyExpr: FnCallExpr = {
        tag: ExprTag.FnCall,
        func: {
          tag: ExprTag.Atom,
          token: {
            type: TokenType.Identifier,
            value: origFuncVarName,
            position: func.token.position,
            modulePath: env.modulePath,
            inputString: env.inputString,
          },
        },
        args: bodyArgs,
        token: func.token,
      };

      // Create parameters frame
      const parametersFrame = {
        id: `pa_frame_${randomId(env.modulePath)}`,
        variables: newParams.map((p) => ({
          id: `pa_var_${randomId(env.modulePath)}`,
          name: p.label,
          type: p.type,
          isCompileTimeOnly: true as const,
          value: undefined,
          token: PlaceholderToken,
          initializedAtToken: PlaceholderToken,
          consumedAtToken: undefined,
          isOwningTheRcValue: false,
          frameLevel: partialEnv.frames.length,
        })),
        isBeginBlockFrame: false,
        whereClauseConstraints: new Map(),
      };

      const newFuncType = createFunctionType({
        parameters: newParams,
        forallParameters: [],
        variadicParameter: undefined,
        return_: { ...origFuncType.return },
        env: partialEnv,
        parametersFrame,
      });

      const newFuncValue: FunctionValue = {
        tag: ValueTag.Function,
        type: newFuncType,
        body: bodyExpr,
        frameLevel: partialEnv.frames.length - 1,
        funcName: `partial_${origFuncValue.funcName ?? "anon"}`,
        funcId: `partial_${randomId(env.modulePath)}`,
        calledComptimeFunctionCaches: [],
        specializedFunctionCaches: [],
      };

      expr.$ = {
        env,
        type: newFuncType,
        value: newFuncValue,
        pathCollection: [],
      };
      return expr;
    }
  }

  // plans/archive/SLICE_REWORK.md Part C — copying range indexing.
  // `recv(a..b)` / `recv(a..=b)` on a RUNTIME receiver that provides
  // slice_copy / slice_copy_inclusive rewrites to that method call
  // (owned-return value semantics: Array/ArrayList ranges copy into a new
  // ArrayList, String ranges into a new String; str stays a zero-copy
  // static window). The Index trait's `*(Output)` pointer contract cannot
  // express owned returns, hence the method dispatch. Comptime-valued
  // receivers (array/slice/comptime_str literals) keep the comptime
  // slicing path in tryToCallWithIndexTrait.
  if (
    !givenFunc &&
    !methodExpr &&
    !forMacroExpansion &&
    functions.length === 1 &&
    args.length === 1 &&
    (exprIsFunctionCallOf(args[0]!, "..", 2) ||
      exprIsFunctionCallOf(args[0]!, "..=", 2))
  ) {
    const recvType = functions[0]!.type;
    const recvValue = functions[0]!.value;
    const recvHasComptimeSliceValue =
      recvValue !== undefined &&
      !isUnknownValue(recvValue) &&
      !isTypeValue(recvValue);
    if (
      !isFunctionType(recvType) &&
      !isTypeValue(recvValue) &&
      !recvHasComptimeSliceValue
    ) {
      const sliceCopyName = exprIsFunctionCallOf(args[0]!, "..=", 2)
        ? "slice_copy_inclusive"
        : "slice_copy";
      const sliceCopyMethods = getReceiverMethodsByNameFromEnv({
        env,
        context,
        methodName: sliceCopyName,
        receiverType: recvType,
        isInfixOperatorCall: false,
      });
      if (sliceCopyMethods.length > 0) {
        const methodAtom: AtomExpr = {
          tag: ExprTag.Atom,
          token: {
            ...expr.func.token,
            value: sliceCopyName,
            type: TokenType.Identifier,
          },
          $: undefined,
        };
        const dotAtom: AtomExpr = {
          tag: ExprTag.Atom,
          token: {
            ...expr.func.token,
            value: ".",
            type: TokenType.Identifier,
          },
          $: undefined,
        };
        const methodAccess: FnCallExpr = {
          tag: ExprTag.FnCall,
          func: dotAtom,
          args: [func, methodAtom],
          token: expr.func.token,
          $: undefined,
        };
        expr.func = methodAccess;
        return evaluateFunctionCall({ expr, env, context });
      }
    }
  }

  // Optimization: Skip the checking phase when there is exactly one callable
  // function-like candidate (plain function type or Impl/Dyn(Fn(...))).
  //
  // Why this is safe:
  // - There is no overload ambiguity to resolve.
  // - The real execution call still performs full argument/type validation.
  // - We avoid doing a clone-based dry run + real run for the same candidate.
  //
  // Why this is important:
  // - Function call checking currently invokes tryToCallFunctionWithArguments
  //   once in checking mode and again in execution mode.
  // - In call-heavy code (e.g., std collections), this doubles hot-path work.
  const isNonTypeCtfeFunction =
    functions.length === 1 &&
    isFunctionType(functions[0]!.type) &&
    functions[0]!.type.return.isCompileTimeOnly &&
    !functions[0]!.type.return.isUnquote &&
    !isTypeHierarchyType(functions[0]!.type.return.type) &&
    functions[0]!.type.forallParameters.length === 0;

  const hasSingleFunctionLikeCandidate =
    functions.length === 1 &&
    (isFunctionType(functions[0]!.type) ||
      ((isSomeType(functions[0]!.type) || isDynType(functions[0]!.type)) &&
        !!extractFnTraitFromType(functions[0]!.type, env)));

  const canSkipCheckingPhase = hasSingleFunctionLikeCandidate;

  // Find the functions whose parameters match the arguments
  const functionsToCall: FunctionToCall[] = canSkipCheckingPhase
    ? functions.map((functionToCall) => ({
        ...functionToCall,
        result: {
          kind: "function" as const,
          result: undefined as unknown as FunctionCallResult, // Will be computed during execution phase
        },
      }))
    : functions.map((functionToCall) => {
        // Use the stored args if available (e.g., with pointer conversion), otherwise use original args
        const argsToUse = functionToCall.args ?? args;

        if (isFunctionType(functionToCall.type)) {
          try {
            // NOTE: We need to pass the cloneExpr expr and argExprs here because
            // we might modify the expressions during the tryToCallFunctionWithArguments
            // We will call tryToCallFunctionWithArguments again later with the original expr and argExprs when we actually call the function
            // We pass skipSpecialization: true to avoid polluting the specialization cache during this checking phase.
            // See docs/SPECIALIZATION_CACHE_PITFALL.md for details.
            // We also clone the env to prevent CTFE pointer mutations from affecting
            // the real environment (which would cause double mutations).
            // We pass skipCtfeExecution: true to avoid executing CTFE functions during checking.
            // We set isInFunctionCallCheckingPhase: true so nested function calls also skip CTFE execution.
            const result = tryToCallFunctionWithArguments({
              functionValue: extractFunctionValue(functionToCall.value),
              functionType: functionToCall.type,
              expr: cloneExpr(expr),
              functionCalleeExpr: func,
              argExprs: argsToUse.map((arg) => cloneExpr(arg)),
              callerEnv: cloneEnvForCTFECheck(env),
              context: {
                ...context,
                isInFunctionCallCheckingPhase: true,
              },
              isMethodCall: Boolean(methodExpr),
              skipSpecialization: true,
              skipCtfeExecution: true,
            });
            return {
              ...functionToCall,
              result: {
                kind: "function",
                result,
              },
            };
          } catch (error) {
            // Re-throw overflow errors immediately - they should not be caught
            if (error instanceof YoError && error.kind === "overflow") {
              throw formatErrorMessages(
                [
                  {
                    token: expr.token,
                    errorMessage: `Failed to call the function:\n`,
                  },
                  ...error.tokenAndErrorList,
                ],
                error.isAssertionError
              );
            }
            return {
              ...functionToCall,
              result: {
                kind: "error",
                error: error as Error | YoError,
              },
            };
          }
        } else if (
          (isSomeType(functionToCall.type) || isDynType(functionToCall.type)) &&
          extractFnTraitFromType(functionToCall.type, env)
        ) {
          // Handle calling a SomeType or DynType that implements Fn (e.g., Impl(Fn(...) -> ...) or Dyn(Fn(...) -> ...))
          const fnTraitType = extractFnTraitFromType(functionToCall.type, env)!;
          try {
            // NOTE: We need to pass the cloneExpr expr and argExprs here because
            // we might modify the expressions during the tryToCallFunctionWithArguments
            // We will call tryToCallFunctionWithArguments again later with the original expr and argExprs when we actually call the function
            // We pass skipSpecialization: true to avoid polluting the specialization cache during this checking phase.
            // See docs/SPECIALIZATION_CACHE_PITFALL.md for details.
            // We also clone the env to prevent CTFE pointer mutations from affecting
            // the real environment (which would cause double mutations).
            // We pass skipCtfeExecution: true to avoid executing CTFE functions during checking.
            // We set isInFunctionCallCheckingPhase: true so nested function calls also skip CTFE execution.
            const result = tryToCallFunctionWithArguments({
              functionValue: extractFunctionValue(functionToCall.value),
              functionType: fnTraitType.isFn.callType,
              expr: cloneExpr(expr),
              functionCalleeExpr: func,
              argExprs: argsToUse.map((arg) => cloneExpr(arg)),
              callerEnv: cloneEnvForCTFECheck(env),
              context: {
                ...context,
                isInFunctionCallCheckingPhase: true,
              },
              isMethodCall: Boolean(methodExpr),
              skipSpecialization: true,
              skipCtfeExecution: true,
            });
            return {
              ...functionToCall,
              result: {
                kind: "function",
                result,
              },
            };
          } catch (error) {
            // Re-throw overflow errors immediately - they should not be caught
            if (error instanceof YoError && error.kind === "overflow") {
              throw formatErrorMessages(
                [
                  {
                    token: expr.token,
                    errorMessage: `Failed to call the function:\n`,
                  },
                  ...error.tokenAndErrorList,
                ],
                error.isAssertionError
              );
            }
            return {
              ...functionToCall,
              result: {
                kind: "error",
                error: error as Error | YoError,
              },
            };
          }
        } else {
          let value = functionToCall.value;

          // Resolve recursive type references before type checking
          if (
            isTypeValue(value) &&
            isSomeType(value.value) &&
            value.value.recursiveTypeRef
          ) {
            const resolvedType = resolveRecursiveTypeRef(
              value.value,
              env,
              context
            );
            if (resolvedType) {
              value = createTypeValue(resolvedType);
              functionToCall.value = value;
              functionToCall.type = value.type;
            }
          }

          // struct value
          if (isTypeValue(value) && isStructType(value.value)) {
            try {
              const result = tryToCallTypeWithArguments({
                typeFields: value.value.fields,
                functionCalleeExpr: func,
                argExprs: argsToUse,
                callerEnv: env,
                context: { ...context },
              });
              return {
                ...functionToCall,
                result: {
                  kind: "type",
                  result,
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // enum value
          else if (isTypeValue(value) && isEnumType(value.value)) {
            const enumType = value.value;
            const selectedVariant = enumType.variants.find(
              (variant) => variant.name === enumType.selectedVariantName
            );
            if (!selectedVariant) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: formatErrorMessage({
                    token: expr.token,
                    errorMessage: `Enum variant not selected for enum type`,
                  }),
                },
              };
            } else {
              try {
                const result = tryToCallTypeWithArguments({
                  typeFields: selectedVariant.fields || [],
                  functionCalleeExpr: func,
                  argExprs: argsToUse,
                  callerEnv: env,
                  context: { ...context },
                });
                return {
                  ...functionToCall,
                  result: {
                    kind: "type",
                    result,
                  },
                };
              } catch (error) {
                return {
                  ...functionToCall,
                  result: {
                    kind: "error",
                    error: error as Error | YoError,
                  },
                };
              }
            }
          }
          // union value
          else if (isTypeValue(value) && isUnionType(value.value)) {
            try {
              const result = tryToCallTypeWithArguments({
                typeFields: value.value.fields,
                functionCalleeExpr: func,
                argExprs: argsToUse,
                callerEnv: env,
                context: { ...context },
                isUnionType: true,
              });
              return {
                ...functionToCall,
                result: {
                  kind: "type",
                  result,
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // struct value
          else if (isTypeValue(value) && isSourceNamespaceType(value.value)) {
            const sourceNamespaceType = value.value;
            try {
              const result = tryToImplementRecordWithArgumentsByRecordType({
                moduleExpr: func,
                sourceNamespaceType: sourceNamespaceType,
                argExprs: argsToUse,
                callerEnv: env,
                context: { ...context },
              });
              return {
                ...functionToCall,
                result: {
                  kind: "record-type",
                  result,
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // trait value
          else if (isTypeValue(value) && isTraitType(value.value)) {
            const traitType = value.value;

            // Check if this is a trait specialization (`:=` arguments)
            // e.g., Iterator(Item := i32) — used in where clauses
            const hasSpecializationArgs = argsToUse.some(
              (arg) =>
                exprIsFunctionCall(arg) && exprIsFunctionCallOf(arg, ":=", 2)
            );

            if (hasSpecializationArgs) {
              try {
                const result = tryToSpecializeTraitType({
                  traitExpr: func,
                  traitType: traitType,
                  argExprs: argsToUse,
                  callerEnv: env,
                  context: { ...context },
                });
                return {
                  ...functionToCall,
                  result: {
                    kind: "trait-specialization",
                    result,
                  },
                };
              } catch (error) {
                return {
                  ...functionToCall,
                  result: {
                    kind: "error",
                    error: error as Error | YoError,
                  },
                };
              }
            }

            try {
              const result = tryToImplementTraitWithArgumentsByTraitType({
                traitExpr: func,
                traitType: traitType,
                argExprs: argsToUse,
                callerEnv: env,
                context: { ...context },
              });
              return {
                ...functionToCall,
                result: {
                  kind: "trait-type",
                  result,
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // function
          else if (isTypeValue(value) && isFunctionType(value.value)) {
            const functionType = value.value;
            try {
              tryToImplementFunctionByFunctionType({
                expr: expr,
                functionType: functionType,
                callerEnv: env,
                context: { ...context },
              });
              return {
                ...functionToCall,
                result: {
                  kind: "function-type",
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // array type
          else if (isTypeValue(value) && isArrayType(value.value)) {
            const arrayType = value.value;
            try {
              tryToImplementArrayByArrayType({
                expr: expr,
                arrayType: arrayType,
                argExprs: argsToUse,
                callerEnv: env,
                context: { ...context },
              });
              return {
                ...functionToCall,
                result: {
                  kind: "array-type",
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // comptime list type
          else if (isTypeValue(value) && isComptimeListType(value.value)) {
            const comptimeListType = value.value;
            try {
              tryToImplementComptimeListByComptimeListType({
                expr: expr,
                comptimeListType: comptimeListType,
                argExprs: argsToUse,
                callerEnv: env,
                context: { ...context },
              });
              return {
                ...functionToCall,
                result: {
                  kind: "array-type",
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // SomeType or DynType that implements Fn (e.g., Impl(Fn(...) -> ...) or Dyn(Fn(...) -> ...))
          else if (
            isTypeValue(value) &&
            (isSomeType(value.value) || isDynType(value.value))
          ) {
            const wrapperType = value.value;
            const fnTraitType = extractFnTraitFromType(wrapperType, env);
            if (fnTraitType) {
              try {
                tryToImplementClosureByFnTraitType({
                  expr: expr,
                  fnTraitType: fnTraitType,
                  wrapperType: wrapperType,
                  callerEnv: env,
                  context: { ...context },
                });
                return {
                  ...functionToCall,
                  result: {
                    kind: "closure-type",
                  },
                };
              } catch (error) {
                return {
                  ...functionToCall,
                  result: {
                    kind: "error",
                    error: error as Error | YoError,
                  },
                };
              }
            } else if (
              isSomeType(wrapperType) &&
              wrapperType.kindFunctionType
            ) {
              // HKT: F(A) where F is an abstract type constructor
              // Create a TypeApplication instead of trying to call
              try {
                const kindFuncType = wrapperType.kindFunctionType;
                const evalArgs: Type[] = [];

                // Validate argument count
                if (argsToUse.length !== kindFuncType.parameters.length) {
                  throw formatErrorMessage({
                    token: func.token,
                    errorMessage: `Type constructor "${wrapperType.name}" expects ${kindFuncType.parameters.length} argument(s), got ${argsToUse.length}`,
                  });
                }

                // Evaluate each arg and extract its type
                for (let ai = 0; ai < argsToUse.length; ai++) {
                  const argExpr = argsToUse[ai]!;
                  const evaluatedArg = evaluateExpression({
                    expr: argExpr,
                    env: env,
                    context: { ...context },
                  });
                  if (!evaluatedArg.$) {
                    throw formatErrorMessage({
                      token: argExpr.token,
                      errorMessage: `Failed to evaluate HKT argument`,
                    });
                  }
                  env = evaluatedArg.$.env;

                  // The arg should be a TypeValue
                  if (!isTypeValue(evaluatedArg.$.value)) {
                    throw formatErrorMessage({
                      token: argExpr.token,
                      errorMessage: `Expected type argument for type constructor "${wrapperType.name}", got:\n${exprToString(argExpr)}`,
                    });
                  }
                  evalArgs.push(evaluatedArg.$.value.value);
                }

                // Create TypeApplication
                const typeApp = createTypeApplicationType(
                  wrapperType,
                  evalArgs,
                  kindFuncType.return.type,
                  env
                );

                const typeAppValue = createTypeValue(typeApp);
                expr.$ = {
                  env,
                  type: typeOfType(typeApp),
                  value: typeAppValue,
                  pathCollection: [],
                };

                return {
                  ...functionToCall,
                  result: {
                    kind: "type",
                    result: {
                      values: [typeAppValue],
                      pathCollection: [],
                      runtimeArgExprsInOrder: [],
                      callerEnv: env,
                    },
                  },
                };
              } catch (error) {
                return {
                  ...functionToCall,
                  result: {
                    kind: "error",
                    error: error as Error | YoError,
                  },
                };
              }
            } else if (
              isSomeType(wrapperType) &&
              wrapperType.recursiveTypeRef
            ) {
              // This is a recursive type reference that couldn't be resolved yet.
              // Allow it to be used as a constructor - the type will be resolved later.
              // We treat this as if calling an object constructor with no field validation.
              try {
                // Evaluate the arguments to type-check them
                const runtimeArgExprsInOrder: Expr[] = [];
                for (const argExpr of argsToUse) {
                  const evaluatedArg = evaluateExpression({
                    expr: argExpr,
                    env: env,
                    context: { ...context },
                  });
                  if (!evaluatedArg.$) {
                    throw formatErrorMessage({
                      token: argExpr.token,
                      errorMessage: `Failed to evaluate argument`,
                    });
                  }
                  env = evaluatedArg.$.env;
                  runtimeArgExprsInOrder.push(evaluatedArg);
                }

                return {
                  ...functionToCall,
                  result: {
                    kind: "type",
                    result: {
                      values: runtimeArgExprsInOrder.map((e) => e.$!.value),
                      pathCollection: [],
                      runtimeArgExprsInOrder,
                      callerEnv: env,
                    },
                  },
                };
              } catch (error) {
                return {
                  ...functionToCall,
                  result: {
                    kind: "error",
                    error: error as Error | YoError,
                  },
                };
              }
            } else {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: formatErrorMessage({
                    token: func.token,
                    errorMessage: `Invalid function call on type:
${isTypeValue(value) ? typeToString(value.value) : typeToString(functionToCall.type)}`,
                  }),
                },
              };
            }
          }
          // array, ComptimeList, comptime_str, or any type with Index impl
          // — unified through Index trait dispatch
          else if (
            isArrayType(functionToCall.type) ||
            (!isTypeValue(value) &&
              hasIndexImpl({
                concreteType: functionToCall.type,
                argExprs: argsToUse,
                callerEnv: env,
                _context: context,
              }))
          ) {
            try {
              const result = tryToCallWithIndexTrait({
                expr,
                valueType: functionToCall.type,
                selfValue: functionToCall.value,
                argExprs: argsToUse,
                callerEnv: env,
                context: { ...context },
              });
              return {
                ...functionToCall,
                result: {
                  kind: "index",
                  result,
                },
              };
            } catch {
              // Index dispatch failed (e.g., generic Array(T,N) where T is
              // a type parameter). Fall through to the fallback path.
            }

            // Fallback for generic types (Array(T,N) where T is a type parameter):
            // return element type with unknown value
            if (isArrayType(functionToCall.type)) {
              const arrayType = functionToCall.type as ArrayType;
              const returnType = arrayType.childType;
              return {
                ...functionToCall,
                result: {
                  kind: "index" as const,
                  result: {
                    value: undefined,
                    type: returnType,
                    ptrType: createPtrType(returnType),
                    indexMethodType: undefined,
                    indexMethodValue: undefined,
                    callerEnv: env,
                  },
                },
              };
            }

            // For non-array/slice types, re-throw as error
            return {
              ...functionToCall,
              result: {
                kind: "error",
                error: formatErrorMessage({
                  token: func.token,
                  errorMessage: `Index trait dispatch failed for type: ${typeToString(functionToCall.type)}`,
                }),
              },
            };
          }
          // numeric type conversion (i32, u8, f64, etc.)
          else if (
            isTypeValue(value) &&
            isConvertibleNumericType(value.value)
          ) {
            const targetType = value.value;
            // Numeric types expect exactly one argument
            if (argsToUse.length !== 1) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: formatErrorMessage({
                    token: func.token,
                    errorMessage: `Numeric type conversion expects exactly 1 argument, got ${argsToUse.length}`,
                  }),
                },
              };
            }
            try {
              const result = tryToConvertToNumericType({
                targetType,
                argExpr: argsToUse[0]!,
                expr,
                callerEnv: env,
                context: { ...context },
              });
              if (result) {
                return {
                  ...functionToCall,
                  result: {
                    kind: "numeric-type",
                    result,
                  },
                };
              } else {
                return {
                  ...functionToCall,
                  result: {
                    kind: "error",
                    error: formatErrorMessage({
                      token: func.token,
                      errorMessage: `Failed to convert to numeric type ${typeToString(targetType)}`,
                    }),
                  },
                };
              }
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // pointer type casting (*(T))
          else if (isTypeValue(value) && isPtrType(value.value)) {
            const targetType = value.value;
            // Pointer type casting expects exactly one argument
            if (argsToUse.length !== 1) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: formatErrorMessage({
                    token: func.token,
                    errorMessage: `Pointer type casting expects exactly 1 argument, got ${argsToUse.length}`,
                  }),
                },
              };
            }
            try {
              const result = tryToConvertToPointerType({
                targetType,
                argExpr: argsToUse[0]!,
                expr,
                callerEnv: env,
                context: { ...context },
              });
              if (result) {
                return {
                  ...functionToCall,
                  result: {
                    kind: "pointer-type",
                    result,
                  },
                };
              } else {
                return {
                  ...functionToCall,
                  result: {
                    kind: "error",
                    error: formatErrorMessage({
                      token: func.token,
                      errorMessage: `Failed to cast to pointer type ${typeToString(targetType)}`,
                    }),
                  },
                };
              }
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          }
          // Iso value constructor: Iso(T)(value)
          else if (isTypeValue(value) && isIsoType(value.value)) {
            const isoType = value.value;
            // Iso value constructor expects exactly one argument
            if (argsToUse.length !== 1) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: formatErrorMessage({
                    token: func.token,
                    errorMessage: `Iso value constructor expects exactly 1 argument, got ${argsToUse.length}`,
                  }),
                },
              };
            }
            try {
              const result = evaluateIsoValueCall({
                expr,
                env,
                context: { ...context },
                isoType,
              });
              return {
                ...functionToCall,
                result: {
                  kind: "iso-value",
                  result,
                },
              };
            } catch (error) {
              return {
                ...functionToCall,
                result: {
                  kind: "error",
                  error: error as Error | YoError,
                },
              };
            }
          } else {
            return {
              ...functionToCall,
              result: {
                kind: "error",
                error: formatErrorMessage({
                  token: func.token,
                  errorMessage: `Invalid function call on type:
${isTypeValue(value) ? typeToString(value.value) : typeToString(functionToCall.type)}`,
                }),
              },
            };
          }
        }
      }); // End of the checking phase map

  let functionsWithMatchingTypes = functionsToCall.filter(
    (functionToCall) => functionToCall.result.kind !== "error"
  );

  // Check if there is only one comptime function call,
  // If yes, then we use that function.
  // Comptime function call has higher priority than normal function call.
  // So this way we eagerly evaluate the function call that can be done at the compile-time.
  //
  // EXCEPTION: When any arg is a runtime-only UnknownValue (e.g., from Index trait
  // dispatch), exclude comptime function candidates. These values represent runtime
  // computations that cannot be evaluated at compile time. Regular UnknownValues
  // (from CTFE analysis) are compile-time placeholders and should still prefer comptime.
  const hasRuntimeUnknownArg = args.some(
    (arg) =>
      arg.$?.value && isUnknownValue(arg.$.value) && arg.$.value.isRuntimeOnly
  );
  const comptimeFunctionCalls = functionsWithMatchingTypes.filter(
    (functionToCall) =>
      isFunctionType(functionToCall.type) &&
      functionToCall.type.return.isCompileTimeOnly // TODO: How about other type calls?
  );

  if (hasRuntimeUnknownArg && comptimeFunctionCalls.length > 0) {
    // Exclude comptime functions — args contain runtime UnknownValues that
    // cannot be evaluated at compile time
    functionsWithMatchingTypes = functionsWithMatchingTypes.filter(
      (f) => !comptimeFunctionCalls.includes(f)
    );
  } else if (comptimeFunctionCalls.length === 1) {
    functionsWithMatchingTypes = comptimeFunctionCalls;
  }

  // When there are still multiple matches and multiple are comptime functions,
  // prefer the one with comptime parameter types over runtime parameter types.
  // For example, when calling `3 > 4`:
  // - Prefer fn(comptime_int, comptime_int) -> bool over fn(i32, i32) -> bool
  // This ensures that compile-time operations stay at compile-time when possible.
  if (functionsWithMatchingTypes.length > 1) {
    const functionsWithComptimeParams = functionsWithMatchingTypes.filter(
      (functionToCall) => {
        if (!isFunctionType(functionToCall.type)) return false;
        const params = functionToCall.type.parameters;
        // Check if any parameter is a comptime type (comptime_int, comptime_float, comptime_str)
        return params.some(
          (param) =>
            isComptimeIntType(param.type) ||
            isComptimeFloatType(param.type) ||
            isComptimeStringType(param.type)
        );
      }
    );
    if (functionsWithComptimeParams.length === 1) {
      functionsWithMatchingTypes = functionsWithComptimeParams;
    }
  }

  if (functionsWithMatchingTypes.length === 0) {
    if (
      functionsToCall.length === 1 &&
      functionsToCall[0]!.result.kind === "error"
    ) {
      const error = functionsToCall[0]!.result.error;
      if (error instanceof YoError) {
        // console.trace(exprToString(expr));
        throw formatErrorMessages(
          [
            {
              token: expr.token,
              errorMessage: `Failed to call the function:\n
${error.tokenAndErrorList
  .filter(({ token }) => token.modulePath !== expr.token.modulePath)
  .map(({ errorMessage }) => `- ${errorMessage}`)
  .join("\n")}`,
            },
            ...error.tokenAndErrorList.filter(
              ({ token }) => token.modulePath === expr.token.modulePath
            ),
          ],
          error.isAssertionError
        );
      } else {
        // console.log("Error type:", error?.constructor?.name);
        // console.log(
        //   "Error message:",
        //   error instanceof Error ? error.message : String(error)
        // );
        // console.log(
        //   "Error stack:",
        //   error instanceof Error
        //     ? error.stack?.split("\n").slice(0, 10).join("\n")
        //     : "no stack"
        // );
        // console.trace(exprToString(expr));
        throw formatErrorMessages([
          {
            token: expr.token,
            errorMessage: `Failed to call the function:\n`,
          },
          {
            token: expr.token,
            errorMessage:
              error instanceof Error ? error.message : String(error),
          },
        ]);
      }
    }

    throw formatErrorMessages([
      {
        token: func.token,
        errorMessage: `No matching call found with arguments:
${exprToString(expr)}

${functionsToCall.length ? "Available functions:\n" : ""}`,
      },
      ...functionsToCall
        .map((functionToCall) => {
          const error =
            functionToCall.result.kind === "error"
              ? functionToCall.result.error
              : undefined;
          if (error) {
            if (error instanceof YoError) {
              return [
                {
                  token: func.token,
                  errorMessage: `- ${typeToString(functionToCall.type)}\n`,
                },
                ...error.tokenAndErrorList,
              ];
            } else {
              return {
                token: func.token,
                errorMessage: `- ${typeToString(functionToCall.type)}\n${error instanceof Error ? error.message : String(error)}`,
              };
            }
          } else {
            return {
              token: func.token,
              errorMessage: `${typeToString(functionToCall.type)}`,
            };
          }
        })
        .flat(),
    ]);
  }
  if (functionsWithMatchingTypes.length > 1) {
    throw formatErrorMessage({
      token: func.token,
      errorMessage: `Ambiguous call with arguments:
${exprToString(expr)}

Found ${functionsWithMatchingTypes.length} matching calls:
${functionsWithMatchingTypes.map((matchedFunction) => `${typeToString(matchedFunction.type)}`).join("\n")}
`,
    });
  }

  const functionToCall = functionsWithMatchingTypes[0]!; // Found the only one function to call

  // plans/archive/EXTERN_UNSAFE_WRAP.md Phase A — extern "c" call-site gate.
  //
  // Calls to functions declared `extern "c"` (via `extern(...)` or
  // `c_include(...)`) must be wrapped in `unsafe(...)` at the call
  // site, even in files declaring `pragma(Pragma.AllowUnsafe);`. The
  // pragma authorizes DECLARING the FFI symbol; this gate is the
  // per-call-site audit marker so `yo unsafe-report` can pinpoint
  // the UB-capable line.
  //
  // Exemptions:
  //  - `context.unsafeContext` — the call is lexically inside an
  //    `unsafe(...)` wrapper (set by evaluateUnsafe).
  //  - `auto-generated://` URIs — macro / derive expansions inherit
  //    privilege from their user-facing trigger site.
  if (
    isFunctionType(functionToCall.type) &&
    functionToCall.type.isExtern === "c" &&
    !context.unsafeContext &&
    !isAutoGeneratedExpansion(expr.token.modulePath)
  ) {
    const calleeName = functionToCall.type.externName ?? exprToString(func);
    // Migration-helper mode (plans/archive/EXTERN_UNSAFE_WRAP.md Phase C):
    // setting `YO_EXTERN_WRAP_DUMP_FILE` makes the gate COLLECT the
    // unwrapped sites instead of throwing, so a single check-pass
    // can produce a JSON list of every site needing `unsafe(...)`.
    // The migration script reads the JSON and applies precise wraps.
    if (process.env.YO_EXTERN_WRAP_DUMP_FILE) {
      recordExternCallSite({
        modulePath: expr.token.modulePath,
        characterOffset: func.token.position.character,
        calleeName,
      });
    } else {
      throw formatErrorMessage({
        token: expr.token,
        errorMessage: `Call to extern "c" function '${calleeName}' must be wrapped in 'unsafe(...)' to mark the call site as audit-capable.

C functions are outside Yo's type-checking reach — wrong argument types, contract violations, or aliasing assumptions produce undefined behavior. Wrapping each call site lets 'yo unsafe-report' flag exactly where the UB-capable operations live, instead of just noting that the whole file is privileged.

Fix: wrap the call:

  unsafe(${exprToString(expr)})`,
      });
    }
  }

  // When we're in a checking phase of an outer function call, AND this function is a CTFE function
  // that returns a non-type compile-time value, we should NOT actually execute it - just return
  // a placeholder with the correct type. This prevents exponential blowup when checking recursive
  // CTFE functions like factorial.
  // The actual execution will happen when the outer function call executes.
  //
  // IMPORTANT: We must NOT skip execution for:
  // 1. Type-returning CTFE functions (Box(V), Vec(T)) - need execution to resolve the type
  // 2. Functions with generic parameters - return type may reference unresolved generic params
  const shouldSkipExecutionDuringChecking =
    context.isInFunctionCallCheckingPhase && isNonTypeCtfeFunction;

  if (shouldSkipExecutionDuringChecking) {
    const functionType = functionToCall.type as FunctionType;
    const { returnType } = evaluateFunctionReturnTypeAgain({
      functionType,
      calleeEnv: functionType.env,
      context: { ...context, isEvaluatingFunctionType: true },
      functionCalleeExpr: func,
    });

    env = popEnvFrame(env);

    expr.$ = {
      env,
      type: returnType,
      value: createUnknownValue(returnType, {
        variableName: "checking_phase_placeholder_" + randomId(env.modulePath),
        env,
        context,
      }),
      pathCollection: [],
    };
    return expr;
  }

  // This function call is for macro expansion.
  // So we just return the expr we expanded.
  if (forMacroExpansion) {
    // It is macro function call
    if (
      isFunctionType(functionToCall.type) &&
      functionToCall.type.return.isUnquote
    ) {
      // Evaluate the function again with the real expr and arg exprs
      const {
        returnValue,
        callerEnv,
        pathCollection,
        deferredDropExpressions,
      } = tryToCallFunctionWithArguments({
        functionValue: extractFunctionValue(functionToCall.value),
        functionType: functionToCall.type,
        expr: expr,
        functionCalleeExpr: func,
        argExprs: functionToCall.args ?? args,
        callerEnv: env,
        context: {
          ...context,
          // Macro expansion must fully evaluate the body to produce the
          // expanded code. Clear validation flags so recursive comptime
          // helpers (recur) and CTFE actually execute instead of short-
          // circuiting to UnknownValue.
          isValidatingFunctionDefinition: false,
          isAnalyzingCtfeCapability: false,
          isExecuting: true,
        },
        isMethodCall: Boolean(methodExpr),
      });

      // const {
      //   returnValue,
      //   callerEnv,
      //   pathCollection,
      //   deferredDropExpressions,
      // } = getFunctionCallResult(functionToCall);

      env = popEnvFrame(callerEnv);

      expr.$ = {
        env,
        type: createExprType(),
        value: returnValue,
        originType: createExprType(), // Macro result's origin type is the expression type
        pathCollection: pathCollection,
        deferredDropExpressions,
      };

      return expr;
    } else {
      throw formatErrorMessage({
        token: func.token,
        errorMessage: `Expected macro function call for macro_expand.`,
      });
    }
  }

  if (isFunctionType(functionToCall.type)) {
    const functionType = functionToCall.type;
    const isMacroCall = functionType.return.isUnquote;

    {
      // It's
      // - Function returns runtime value
      // - Function returns comptime value
      // For function returns comptime value, we can evaluate the function body.
      // Evaluate the function again with the real expr and arg exprs
      const {
        returnType,
        returnValue,
        callerEnv,
        // calleeEnv,
        // argValues,
        pathCollection,
        specializedFunctionValue,
        runtimeArgExprsInOrder,
        deferredDropExpressions,
      } = tryToCallFunctionWithArguments({
        functionValue: extractFunctionValue(functionToCall.value),
        functionType: functionToCall.type,
        expr: expr,
        functionCalleeExpr: func,
        argExprs: functionToCall.args ?? args,
        callerEnv: env,
        context: isMacroCall
          ? {
              ...context,
              // Macro expansion must fully evaluate the body to produce the
              // expanded code. Clear validation flags so recursive comptime
              // helpers (recur) and CTFE actually execute instead of short-
              // circuiting to UnknownValue.
              isValidatingFunctionDefinition: false,
              isAnalyzingCtfeCapability: false,
              isExecuting: true,
            }
          : context,
        isMethodCall: Boolean(methodExpr),
      });

      env = popEnvFrame(callerEnv);

      // Check if it's a macro function call,
      // if yes, then we continue to evaluate the returnValue which should be an Expr value.
      if (functionType.return.isUnquote) {
        if (isExprValue(returnValue)) {
          const expandedExpr = evaluateExpression({
            expr: returnValue.value,
            env,
            context: {
              ...context,
            },
          });

          // Store the expanded expression on the original expr for C codegen
          expr.$ = {
            env: expandedExpr.$?.env || env,
            type: expandedExpr.$?.type || returnType,
            value: expandedExpr.$?.value,
            originType:
              expandedExpr.$?.originType || expandedExpr.$?.type || returnType,
            pathCollection: expandedExpr.$?.pathCollection || [],
            macroExpansion: expandedExpr,
            // IMPORTANT: Copy variableName from expanded expression for ownership tracking
            variableName: expandedExpr.$?.variableName,
          };

          return expr;
        } else {
          throw formatErrorMessage({
            token: expr.token,
            errorMessage: `Expected macro function to return an Expr value, got:\n${valueToString(
              returnValue
            )}`,
          });
        }
      }

      // No consumption logic needed anymore

      // Preserve the variableName if it was already set (e.g., from a previous overload attempt)
      const previousVariableName = expr.$?.variableName;

      // For functions returning plain Impl(...) (SomeType), set resolvedConcreteType
      // to the concrete type from the function body.  This enables static dispatch
      // for method calls on the return value.
      let finalReturnType = returnType;
      if (isSomeType(returnType)) {
        if (functionToCall.value && isFunctionValue(functionToCall.value)) {
          const functionBody = functionToCall.value.body;
          if (functionBody.$?.type) {
            // If the function body's type is also a SomeType with resolvedConcreteType,
            // use that concrete type directly. This is important for async blocks which
            // return SomeType(Impl(Future)) with resolvedConcreteType set to the capture struct.
            let concreteType = functionBody.$.type;
            if (isSomeType(concreteType) && concreteType.resolvedConcreteType) {
              concreteType = concreteType.resolvedConcreteType;
            }
            // Clone the SomeType and set its resolvedConcreteType
            finalReturnType = {
              ...returnType,
              resolvedConcreteType: concreteType,
            } as SomeType;
          }
        } else if (
          isFunctionType(functionToCall.type) &&
          functionToCall.type.return?.type &&
          !isSomeType(functionToCall.type.return.type)
        ) {
          // For extern C functions (and others without a FunctionValue body),
          // use the declared return type from the function signature.
          // This ensures generic type parameters (e.g., _Self in `not`) get
          // resolvedConcreteType set so specialization works correctly.
          finalReturnType = {
            ...returnType,
            resolvedConcreteType: functionToCall.type.return.type,
          } as SomeType;
        }
      }

      expr.$ = {
        env,
        type: finalReturnType,
        value: returnValue,
        originType: finalReturnType, // Function call result's origin type is its return type
        pathCollection: pathCollection,
        runtimeArgExprsInOrder,
        deferredDropExpressions,
        variableName: previousVariableName,
      };

      // isControlFunction with generic parameters that was specialized inline: mark
      // the call expression with escape control flow. After specialization the
      // effective return type matches the enclosing function's return type (e.g. unit
      // → void). The "unwind" annotation lets match arms treat this call as
      // "never-type" so type unification with other arms works correctly.
      // Do NOT set escape for isControlFunction calls that were NOT specialized
      // (e.g. `Raise :: fn(...) -> i32`); those have a meaningful return type that
      // must remain visible to the enclosing type-checker.
      if (
        isFunctionValue(functionToCall.value) &&
        functionToCall.value.isControlFunction &&
        specializedFunctionValue !== undefined
      ) {
        expr.$.controlFlow = controlFlowOf("unwind");
      }

      // NOTE: A previous version (commit f51ad0d3) added a "parametricity"
      // detection here that marked calls like `exn.throw(...)` as
      // controlFlow="unwind" so the begin-block evaluator would skip
      // subsequent dead code (like `t_i32()` constructor calls).
      // That detection was reverted because it also fired on calls inside
      // async closures whose closure parameters wrap generic-T inside
      // Impl(Fn(...) -> T) (which `typeContainsSomeType` does not look
      // through), and on user code with explicit `return` statements after
      // a `raise(...)`-style escape — breaking closure return-type
      // inference for tests like `tests/async_await.test.yo`'s
      // "Test escape in async closure".
      // See `issues/codegen-dead-code-after-exn-throw.md` for the original
      // problem this was trying to solve.

      // For io.async calls, propagate awaitAnalysis and captureType from the closure
      // argument to the call expression. This enables codegen to generate a state machine
      // instead of a sync future when the closure contains await points.
      if (functionType.ioBuiltin === "io_async" && runtimeArgExprsInOrder[0]) {
        const closureArg = runtimeArgExprsInOrder[0];
        const closureFnValue = closureArg.$?.closureFunctionValue as
          | FunctionValue
          | undefined;

        // Propagate the closure's annotated bundle type (the E in
        // Impl(Fn(e : E) -> T)) into the return type Impl(Future(T, E)).
        // The anonymous-function evaluator substitutes E inside the lambda's
        // own functionType, but the outer return type SomeType remains
        // unresolved. Downstream `(task : Impl(Future(_, Ctx))) = io.async(...)`
        // annotations reject the value as `Impl(Future(_, E))` without this.
        // See [[yo-anon-closure-param-name-extraction]].
        if (
          closureFnValue &&
          isFunctionType(closureFnValue.type) &&
          closureFnValue.type.parameters.length > 0
        ) {
          const bundleType = closureFnValue.type.parameters[0]!.type;
          if (!isSomeType(bundleType)) {
            const futureTraitForReturn = extractFutureTraitFromType(returnType);
            const eSomeType = futureTraitForReturn?.isFuture.effect?.type;
            if (
              eSomeType &&
              isSomeType(eSomeType) &&
              !eSomeType.resolvedConcreteType
            ) {
              eSomeType.resolvedConcreteType = bundleType;
            }
          }
        }
        if (closureFnValue?.body?.$?.awaitAnalysis) {
          expr.$.awaitAnalysis = closureFnValue.body.$.awaitAnalysis;
          expr.$.captureType = closureArg.$?.captureType;
          expr.$.deferredDupExpressions = closureArg.$?.deferredDupExpressions;
          // Clear from closure to prevent the dup/drop optimizer from collecting
          // these dups twice (once on io.async, once on the closure argument).
          if (closureArg.$?.deferredDupExpressions) {
            closureArg.$.deferredDupExpressions = undefined;
          }

          // Mark closure-captured variables as "outer" in the await analysis.
          // These variables live in the __capture struct, not as local SM fields.
          const closureCaptureType = closureArg.$?.captureType;
          if (closureCaptureType && expr.$.awaitAnalysis) {
            const captureFieldNames = new Set(
              closureCaptureType.fields.map((f: { label: string }) => f.label)
            );
            expr.$.awaitAnalysis = {
              ...expr.$.awaitAnalysis,
              capturedVariables: expr.$.awaitAnalysis.capturedVariables.map(
                (v) =>
                  captureFieldNames.has(v.name)
                    ? { ...v, kind: "outer" as const }
                    : v
              ),
            };
          }

          // Mark the closure so codegen skips generating its C function
          // (the body is handled by the state machine's resume function)
          closureFnValue.isIoAsyncStateMachineClosure = true;
        } else {
          // Sync path (no await points in the closure body).
          // The closure's capture struct is stack-allocated (Impl closure),
          // so captures are just borrowed pointers — no RC dups needed.
          // Clear deferredDupExpressions to prevent closures.ts from
          // generating unnecessary dups that would leak (no matching Drop
          // on stack-allocated capture structs).
          if (closureArg.$?.deferredDupExpressions) {
            closureArg.$.deferredDupExpressions = undefined;
          }
        }

        // Mark the closure's temp variable as consumed so it won't get a
        // deferred drop in the parent scope — the capture struct is either
        // owned by the state machine (async path) or stack-allocated (sync path).
        // In either case, the evaluator's temp variable name doesn't correspond
        // to a declared C variable, so a scope-exit drop would reference an
        // undeclared identifier.
        const closureVarName = closureArg.$?.variableName;
        if (closureVarName && expr.$.env) {
          const vars = getVariablesFromEnv(expr.$.env, closureVarName);
          const closureVar = vars[vars.length - 1];
          if (closureVar) {
            expr.$.env = updateExistingVariable(expr.$.env, closureVar, {
              ...closureVar,
              consumedAtToken: expr.token,
            });
          }
        }
      }

      // Set temp variable which holds the result of the function call.
      // For `-> ref(T)` returning calls, mark the temp as `isRef` so
      // the codegen declares it `T*` (matching the call's actual C
      // return type) and atom reads auto-deref via the existing
      // ref-aware atom emitter. See plans/archive/ITERATOR_REDESIGN.md
      // Phase B.
      const callReturnIsRef =
        isFunctionType(functionToCall.type) &&
        functionToCall.type.return.isRef === true;
      attachTempVariableToExpr(expr, true, undefined, callReturnIsRef);

      // Attach necessary info to the func.
      // Preserve runtimeArgExprsInOrder and deferredDropExpressions if func was
      // a pre-evaluated function call (chained call pattern like `opt.unwrap()(args)`).
      const isChainedCallCallee = exprIsFunctionCall(func);
      func.$ = {
        env,
        type: functionToCall.type,
        value: specializedFunctionValue || functionToCall.value,
        pathCollection: [],
        runtimeArgExprsInOrder: func.$?.runtimeArgExprsInOrder,
        deferredDropExpressions: func.$?.deferredDropExpressions,
        variableName: isChainedCallCallee ? func.$?.variableName : undefined,
      };
      if (methodExpr) {
        methodExpr.$ = {
          env,
          type: functionToCall.type,
          value: specializedFunctionValue || functionToCall.value,
          pathCollection: [],
        };
      }
    }

    return expr;
  } else if (
    // Check if it's a closure call
    (isSomeType(functionToCall.type) || isDynType(functionToCall.type)) &&
    extractFnTraitFromType(functionToCall.type, env)
  ) {
    // Handle calling a SomeType or DynType that implements Fn (e.g., Impl(Fn(...) -> ...) or Dyn(Fn(...) -> ...))
    const fnTraitType = extractFnTraitFromType(functionToCall.type, env)!;

    // Re-call tryToCallFunctionWithArguments with the ORIGINAL args (not clones).
    // The checking phase used cloned args (which get $ annotations but are discarded),
    // so the original arg expressions still lack $ annotations.
    // This real call evaluates the original args in-place, setting their $ fields,
    // which is necessary for codegen (e.g., effect state machine generation needs
    // annotated sub-expressions like arr(i) in callback(arr(i))).
    const {
      returnType,
      returnValue,
      callerEnv,
      pathCollection,
      specializedFunctionValue,
      runtimeArgExprsInOrder,
      deferredDropExpressions,
    } = tryToCallFunctionWithArguments({
      functionValue: extractFunctionValue(functionToCall.value),
      functionType: fnTraitType.isFn.callType,
      expr: expr,
      functionCalleeExpr: func,
      argExprs: functionToCall.args ?? args,
      callerEnv: env,
      context,
      isMethodCall: Boolean(methodExpr),
    });

    env = popEnvFrame(callerEnv);

    // Check if it's a macro function call,
    // if yes, then we continue to evaluate the returnValue which should be an Expr value.
    if (fnTraitType.isFn.callType.return.isUnquote) {
      if (isExprValue(returnValue)) {
        const expandedExpr = evaluateExpression({
          expr: returnValue.value,
          env,
          context: {
            ...context,
          },
        });

        // Store the expanded expression on the original expr for C codegen
        expr.$ = {
          env: expandedExpr.$?.env || env,
          type: expandedExpr.$?.type || returnType,
          value: expandedExpr.$?.value,
          originType:
            expandedExpr.$?.originType || expandedExpr.$?.type || returnType,
          pathCollection: expandedExpr.$?.pathCollection || [],
          macroExpansion: expandedExpr,
        };

        return expr;
      } else {
        throw formatErrorMessage({
          token: expr.token,
          errorMessage: `Expected macro closure to return an Expr value, got:\n${valueToString(
            returnValue
          )}`,
        });
      }
    }

    expr.$ = {
      env,
      type: returnType,
      value: returnValue,
      originType: returnType, // Function call result's origin type is its return type
      pathCollection: pathCollection,
      runtimeArgExprsInOrder,
      deferredDropExpressions,
    };

    // Set temp variable which holds the result of the function call
    attachTempVariableToExpr(expr, true);

    // Attach necessary info to the func.
    // Preserve runtimeArgExprsInOrder and deferredDropExpressions if func was
    // a pre-evaluated function call (chained call pattern like `opt.unwrap()(args)`).
    const isChainedCallCallee = exprIsFunctionCall(func);
    // If the resolved value is a plain top-level FunctionValue (not a closure
    // value), expose its concrete FunctionType on `func.$.type` so codegen takes
    // the direct-call path instead of the closure-call (`.call(.data)`) path.
    // This handles `(f)(args)` where f : F with where(F <: Fn(...)) is bound
    // to a top-level named function.
    const resolvedFuncValue = specializedFunctionValue || functionToCall.value;
    let funcExprType: Type = functionToCall.type;
    if (
      isSomeType(functionToCall.type) &&
      isFunctionValue(resolvedFuncValue) &&
      isFunctionType(
        resolvedFuncValue.specializedType ?? resolvedFuncValue.type
      )
    ) {
      funcExprType =
        resolvedFuncValue.specializedType ?? resolvedFuncValue.type;
    }
    func.$ = {
      env,
      type: funcExprType,
      value: resolvedFuncValue,
      pathCollection: [],
      runtimeArgExprsInOrder: func.$?.runtimeArgExprsInOrder,
      deferredDropExpressions: func.$?.deferredDropExpressions,
      variableName: isChainedCallCallee ? func.$?.variableName : undefined,
    };
    if (methodExpr) {
      methodExpr.$ = {
        env,
        type: funcExprType,
        value: resolvedFuncValue,
        pathCollection: [],
      };
    }
    return expr;
  } else {
    const functionToCallValue = functionToCall.value;
    // struct value
    if (
      isTypeValue(functionToCallValue) &&
      isStructType(functionToCallValue.value)
    ) {
      const structType = functionToCallValue.value;
      expr.$ = {
        env,
        type: structType,
        originType: structType, // Struct constructor result's origin type is the struct type
        pathCollection: [],
      };

      const {
        values: memberValues,
        pathCollection,
        callerEnv,
        runtimeArgExprsInOrder,
      } = getTypeCallResult(functionToCall);
      env = callerEnv;
      if (!memberValues) {
        throw formatErrorMessage({
          token: func.token,
          errorMessage: `Error evaluating struct call.`,
        });
      }
      const structValue = memberValues.some(
        (memberValue) =>
          !memberValue ||
          (isUnknownValue(memberValue) && memberValue.isRuntimeOnly)
      )
        ? undefined
        : createStructValue(structType, memberValues as Value[]);
      expr.$.value = isReferenceStructType(structType)
        ? undefined // `object` type only supports runtime value
        : structValue;
      expr.$.pathCollection = pathCollection;
      expr.$.env = env;
      expr.$.runtimeArgExprsInOrder = runtimeArgExprsInOrder;

      // Set temp variable which holds the result of the function call.
      // For `-> ref(T)` returning calls, mark the temp as `isRef` so
      // the codegen declares it `T*` (matching the call's actual C
      // return type) and atom reads auto-deref via the existing
      // ref-aware atom emitter. See plans/archive/ITERATOR_REDESIGN.md
      // Phase B.
      const callReturnIsRef =
        isFunctionType(functionToCall.type) &&
        functionToCall.type.return.isRef === true;
      attachTempVariableToExpr(expr, true, undefined, callReturnIsRef);

      // Attach necessary info to the func
      func.$ = {
        env,
        type: functionToCallValue.type,
        value: functionToCallValue,
        pathCollection: [],
      };
      return expr;
    }
    // enum value
    else if (
      isTypeValue(functionToCallValue) &&
      isEnumType(functionToCallValue.value)
    ) {
      const enumType = functionToCallValue.value;
      expr.$ = {
        env,
        type: enumType,
        originType: enumType, // Enum constructor result's origin type is the enum type
        pathCollection: [],
      };
      // FIXME: Support to set value for comptime
      const selectedVariant = enumType.variants.find(
        (variant) => variant.name === enumType.selectedVariantName
      );
      if (!selectedVariant) {
        throw formatErrorMessage({
          token: expr.token,
          errorMessage: `Enum variant not selected for enum type`,
        });
      }
      const {
        values: memberValues,
        pathCollection,
        callerEnv,
        runtimeArgExprsInOrder,
      } = getTypeCallResult(functionToCall);
      env = callerEnv;

      if (
        memberValues.every(
          (v) => !!v && !(isUnknownValue(v) && v.isRuntimeOnly)
        )
      ) {
        const enumValue = createEnumValue(
          enumType,
          selectedVariant.name,
          memberValues as Value[]
        );
        expr.$.value = enumValue;
      }
      expr.$.pathCollection = pathCollection;
      expr.$.env = env;
      expr.$.runtimeArgExprsInOrder = runtimeArgExprsInOrder;

      // Set temp variable which holds the result of the function call.
      // For `-> ref(T)` returning calls, mark the temp as `isRef` so
      // the codegen declares it `T*` (matching the call's actual C
      // return type) and atom reads auto-deref via the existing
      // ref-aware atom emitter. See plans/archive/ITERATOR_REDESIGN.md
      // Phase B.
      const callReturnIsRef =
        isFunctionType(functionToCall.type) &&
        functionToCall.type.return.isRef === true;
      attachTempVariableToExpr(expr, true, undefined, callReturnIsRef);

      // Attach necessary info to the func
      func.$ = {
        env,
        type: functionToCallValue.type,
        value: functionToCallValue,
        pathCollection: [],
      };
      return expr;
    }
    // union value
    else if (
      isTypeValue(functionToCallValue) &&
      isUnionType(functionToCallValue.value)
    ) {
      const unionType = functionToCallValue.value;
      expr.$ = {
        env,
        type: unionType,
        originType: unionType, // Union constructor result's origin type is the union type
        pathCollection: [],
      };
      const { pathCollection, callerEnv, runtimeArgExprsInOrder } =
        getTypeCallResult(functionToCall);
      env = callerEnv;
      expr.$.value = undefined;
      expr.$.pathCollection = pathCollection;
      expr.$.env = env;
      expr.$.runtimeArgExprsInOrder = runtimeArgExprsInOrder;

      // Set temp variable which holds the result of the function call.
      // For `-> ref(T)` returning calls, mark the temp as `isRef` so
      // the codegen declares it `T*` (matching the call's actual C
      // return type) and atom reads auto-deref via the existing
      // ref-aware atom emitter. See plans/archive/ITERATOR_REDESIGN.md
      // Phase B.
      const callReturnIsRef =
        isFunctionType(functionToCall.type) &&
        functionToCall.type.return.isRef === true;
      attachTempVariableToExpr(expr, true, undefined, callReturnIsRef);

      // Attach necessary info to the func
      func.$ = {
        env,
        type: functionToCallValue.type,
        value: functionToCallValue,
        pathCollection: [],
      };
      return expr;
    }
    // struct value
    else if (
      isTypeValue(functionToCallValue) &&
      isSourceNamespaceType(functionToCallValue.value)
    ) {
      const { moduleValue, callerEnv } =
        getRecordTypeCallResult(functionToCall);
      env = callerEnv;

      expr.$ = {
        env,
        type: moduleValue.type,
        value: moduleValue,
        originType: moduleValue.type, // Record result's origin type is its type
        pathCollection: [],
      };

      // Attach necessary info to the func
      func.$ = {
        env,
        type: functionToCallValue.type,
        value: functionToCallValue,
        pathCollection: [],
      };
      return expr;
    }
    // trait value or trait specialization
    else if (
      isTypeValue(functionToCallValue) &&
      isTraitType(functionToCallValue.value)
    ) {
      // Handle trait specialization: Iterator(Item := i32) → TypeValue
      if (functionToCall.result.kind === "trait-specialization") {
        const result = functionToCall.result.result;
        env = result.callerEnv;
        const typeValue = createTypeValue(result.specializedTraitType);

        expr.$ = {
          env,
          type: typeValue.type,
          value: typeValue,
          pathCollection: [],
        };

        func.$ = {
          env,
          type: functionToCallValue.type,
          value: functionToCallValue,
          pathCollection: [],
        };
        return expr;
      }

      // Handle trait value creation: Iterator(Item : i32, next : body) → TraitValue
      const { traitValue, callerEnv } = getTraitTypeCallResult(functionToCall);
      env = callerEnv;

      expr.$ = {
        env,
        type: traitValue.type,
        value: traitValue,
        originType: traitValue.type, // Trait result's origin type is its type
        pathCollection: [],
      };

      // Attach necessary info to the func
      func.$ = {
        env,
        type: functionToCallValue.type,
        value: functionToCallValue,
        pathCollection: [],
      };
      return expr;
    }
    // function value
    else if (
      isTypeValue(functionToCallValue) &&
      isFunctionType(functionToCallValue.value)
    ) {
      // This should already be evaluated.
      /*
        if (!expr.$ || !expr.$.value) {
          throw formatErrorMessage(
            func.token,
            `Expected function value for function call, got:\n${exprToString(
              expr
            )}`
          );
        }
        */
      return expr;
    }
    // array type
    else if (
      isTypeValue(functionToCallValue) &&
      isArrayType(functionToCallValue.value)
    ) {
      // This should already be evaluated by tryToImplementArrayByArrayType
      return expr;
    }
    // comptime list type
    else if (
      isTypeValue(functionToCallValue) &&
      isComptimeListType(functionToCallValue.value)
    ) {
      // This should already be evaluated by tryToImplementComptimeListByComptimeListType
      return expr;
    }
    // SomeType or DynType - check if it was called as a constructor (has "type" result)
    else if (
      isTypeValue(functionToCallValue) &&
      (isSomeType(functionToCallValue.value) ||
        isDynType(functionToCallValue.value))
    ) {
      // Check if this was a constructor call (has "type" result with recursiveTypeRef)
      if (
        functionToCall.result.kind === "type" &&
        isSomeType(functionToCallValue.value) &&
        functionToCallValue.value.recursiveTypeRef
      ) {
        const someType = functionToCallValue.value;
        expr.$ = {
          env,
          type: someType,
          originType: someType,
          pathCollection: [],
        };

        const { pathCollection, callerEnv, runtimeArgExprsInOrder } =
          getTypeCallResult(functionToCall);
        env = callerEnv;
        expr.$.value = undefined; // Runtime value only
        expr.$.pathCollection = pathCollection;
        expr.$.env = env;
        expr.$.runtimeArgExprsInOrder = runtimeArgExprsInOrder;

        // Set temp variable which holds the result of the function call
        attachTempVariableToExpr(expr, true);

        // Attach necessary info to the func
        func.$ = {
          env,
          type: functionToCallValue.type,
          value: functionToCallValue,
          pathCollection: [],
        };
        return expr;
      }
      // Otherwise it was already evaluated in the first pass (e.g., closure call)
      return expr;
    }
    // numeric type conversion (i32, u8, f64, etc.)
    else if (
      isTypeValue(functionToCallValue) &&
      isConvertibleNumericType(functionToCallValue.value)
    ) {
      // This should already be evaluated by tryToConvertToNumericType
      // The expr has been transformed to __yo_as call if needed
      return expr;
    }
    // pointer type casting (*(T))
    else if (
      isTypeValue(functionToCallValue) &&
      isPtrType(functionToCallValue.value)
    ) {
      // This should already be evaluated by tryToConvertToPointerType
      // The expr has been transformed to __yo_as call if needed
      return expr;
    }
    // Iso value constructor: Iso(T)(value)
    else if (
      isTypeValue(functionToCallValue) &&
      isIsoType(functionToCallValue.value)
    ) {
      // This should already be evaluated by evaluateIsoValueCall
      return expr;
    }
    // Index trait dispatch and comptime array/slice access: value(arg)
    else if (functionToCall.result.kind === "index") {
      const {
        value,
        type,
        ptrType,
        indexMethodType,
        indexMethodValue,
        callerEnv,
        index,
        comptimeRef,
      } = getIndexCallResult(functionToCall);

      // Build pathCollection for compile-time array element access (assignment support)
      let pathCollection = func.$?.pathCollection ?? [];
      if (args.length === 1 && typeof index === "number") {
        if (pathCollection.length > 0) {
          pathCollection = pathCollection.map((path) => [
            ...path,
            index.toString(),
          ]);
        } else if (func.$?.variableName) {
          pathCollection = [[func.$.variableName, index.toString()]];
        }
      }

      expr.$ = {
        env: callerEnv,
        type: type,
        value: value,
        originType: func.$?.originType ?? functionToCall.type,
        pathCollection: pathCollection,
        sourceVariable: func.$?.sourceVariable,
        // Mark as Index trait call so &(value(i)) can skip the auto-deref
        indexTraitPtrType: ptrType,
        indexMethodType: indexMethodType,
        indexMethodValue: indexMethodValue,
        comptimeRef,
        isAccessingProperty: true,
      };

      // Attach necessary info to the func, preserving runtimeArgExprsInOrder
      // and deferredDropExpressions from the inner function call evaluation
      // so that the codegen can generate the call properly.
      func.$ = {
        env,
        type: functionToCall.type,
        value: functionToCall.value,
        pathCollection: func.$?.pathCollection ?? [],
        isAccessingProperty: true,
        runtimeArgExprsInOrder: func.$?.runtimeArgExprsInOrder,
        deferredDropExpressions: func.$?.deferredDropExpressions,
        variableName: func.$?.variableName,
      };

      attachTempVariableToExpr(expr, false);

      return expr;
    }
  }

  throw formatErrorMessage({
    token: expr.token,
    errorMessage: `Function call is not implemented yet:
${exprToString(expr)}`,
  });
}
